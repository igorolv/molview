// --- таблицы ---------------------------------------------------------------

function makeTable(header, rows, widths) {
  const total = widths.reduce((s, w) => s + w, 0);
  const cell = (text, width, opts = {}) => new TableCell({
    width: { size: width, type: WidthType.DXA },
    shading: opts.head ? { type: ShadingType.CLEAR, fill: 'E8EDF5' } : undefined,
    margins: { top: 60, bottom: 60, left: 90, right: 90 },
    children: [new Paragraph({
      children: [new TextRun({ text, bold: !!opts.head, size: 24 })],
      alignment: opts.align ?? (opts.head ? AlignmentType.CENTER : AlignmentType.LEFT),
      spacing: { line: 240 },
      indent: { firstLine: 0 },
    })],
  });

  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({
        tableHeader: true,
        children: header.map((x, k) => cell(x, widths[k], { head: true })),
      }),
      ...rows.map((r) => new TableRow({
        children: r.map((x, k) => cell(String(x), widths[k], {
          align: k === 0 ? AlignmentType.LEFT : AlignmentType.CENTER,
        })),
      })),
    ],
  });
}

