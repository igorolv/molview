#pragma once

/**
 * ВОЛНОВЫЕ ФУНКЦИИ 2s И 2p, ГИБРИДНЫЕ ОРБИТАЛИ НА СЕТКЕ
 *
 * Во второй версии программы лепестки орбиталей были нарисованы кривыми Безье
 * «на глаз». Здесь они считаются: модуль даёт значения ψ в узлах куба, а
 * показывает их сцена изоповерхностями по уровням +iso и −iso.
 *
 * Направления гибридов здесь НЕ выводятся. Их уже посчитала теория Гиллеспи —
 * они лежат в AtomAnalysis::orbitalDirs. Задача этого модуля ровно одна: по
 * направлению построить функцию. Зато тетраэдрический угол 109,47° после этого
 * не постулируется, а проверяется: углы между осями посчитанных гибридов
 * обязаны сойтись с ним сами (tests/orbitaltest.cpp).
 *
 * Про Windows и про VTK модуль не знает — как и весь chem/.
 */

#include <vector>

#include "chem/vec.h"

namespace chem {

/** Радиус Бора в ангстремах: формулы записаны в атомных единицах, сетка — в Å. */
constexpr double BOHR = 0.52917721067;

/** Что считать в узлах сетки. */
enum class Orbital {
    S,    /**< 2s */
    P,    /**< 2p вдоль направления dir */
    Sp,   /**< гибрид sp:  (s + p_d)/√2 */
    Sp2,  /**< гибрид sp²: s/√3 + p_d·√(2/3) */
    Sp3,  /**< гибрид sp³: s/2 + p_d·√3/2 */
};

/**
 * Радиальная часть 2s. У 2p она в обоих случаях одна и та же — r·e^(−r/2).
 *
 * Hydrogen — то, что записано в задании: точное решение для одного электрона
 * в поле ядра, ψ₂s ∝ (2 − r)e^(−r/2). У неё есть радиальный УЗЕЛ при r = 2:
 * дальше него 2s меняет знак, и в гибриде отрицательная часть расплывается
 * широким конусом вокруг обратного направления. Считать так правильно, а
 * СМОТРЕТЬ не на что: четыре такие sp³-орбитали сливаются в шар (раздел 11
 * задания).
 *
 * Slater — приближение Слейтера, ψ₂s ∝ r·e^(−r/2), узла нет. Оно и стоит за
 * учебными картинками: гибрид получается с большим лепестком вперёд и вдвое
 * меньшим назад, а узловая поверхность sp³ оказывается конусом ровно под
 * 109,47°. Все проверяемые свойства (нормировка, узловая плоскость p,
 * ортонормированность, углы между осями) у обеих форм одинаковы — обе и
 * проверяются.
 */
enum class Radial { Hydrogen, Slater };

/**
 * Гибрид по стерическому числу — как его выбирает теория Гиллеспи.
 * Стерические числа 5 и 6 (sp³d, sp³d²) в задании не описаны: d-орбиталей
 * здесь нет, и лепесток для них строится коэффициентами sp³. По направлению
 * он верен, по форме приблизителен, и это единственное место модуля, где
 * картинка не равна формуле.
 */
Orbital orbitalForSteric(int steric);

/** Чем задаётся сетка. */
struct OrbitalOptions {
    /**
     * Узлов по ребру куба. Нечётное — иначе в сетку не попадут ни центр атома,
     * ни узловая плоскость p-орбитали, а на них держатся проверки. Чётное
     * молча увеличивается на единицу.
     */
    int size = 65;
    /** Половина ребра куба, Å. */
    double half = 3.0;
    /**
     * Эффективный заряд ядра: переход r → zeff·r с нормировкой ×zeff^(3/2).
     *
     * В формулах задания он равен единице, то есть это возбуждённые состояния
     * АТОМА ВОДОРОДА — они вчетверо крупнее валентных орбиталей кислорода и на
     * картинке накрыли бы молекулу целиком. Заряд меняет только масштаб длины:
     * ни нормировка, ни узлы, ни углы между гибридами от него не зависят.
     * Выбор заряда — решение показа и живёт в render/.
     */
    double zeff = 1.0;
    Radial radial = Radial::Hydrogen;
};

/** Значения волновой функции в узлах куба вокруг центра атома. */
struct OrbitalGrid {
    int size = 0;
    /** Половина ребра куба, Å. */
    double half = 0;
    /** Центр атома, Å. */
    Vec3 center;
    /** Значения в Å^(−3/2); индекс узла i + size·(j + size·k). */
    std::vector<double> values;

    double step() const { return size > 1 ? 2 * half / (size - 1) : 0.0; }
    double cellVolume() const { const double s = step(); return s * s * s; }
    /** Координата узла, Å. */
    Vec3 point(int i, int j, int k) const;
    double at(int i, int j, int k) const {
        return values[static_cast<std::size_t>(i) +
                      static_cast<std::size_t>(size) *
                          (static_cast<std::size_t>(j) + static_cast<std::size_t>(size) * k)];
    }
    /** Наибольшее |ψ| по сетке. */
    double peak() const;
    /**
     * Наибольшее и наименьшее значение ψ по сетке — с их знаками.
     *
     * Нужны порознь, потому что уровни двух изоповерхностей гибрида приходится
     * задавать порознь: обратный лепесток слабее переднего вдвое у sp³ и
     * вчетверо у sp, и на общем уровне он либо не появится вовсе, либо
     * заставит опустить уровень так, что передние лепестки сольются.
     */
    double highest() const;
    double lowest() const;
    /**
     * Ось орбитали — направление, в которое смещена её амплитуда: ∫ψ·r dV.
     *
     * Искать ось по наибольшему ψ нельзя. У водородоподобных гибридов максимум
     * приходится РОВНО НА ЯДРО (там 2s даёт 2a, а p-часть ноль), у
     * слейтеровских ядро вообще нулевое — направления в такой точке нет.
     *
     * Первый момент же лежит строго вдоль d, и это видно из формулы:
     * s-часть сферически симметрична и в момент не даёт ничего, а от p-части
     * остаётся Σ_j d_j·∫ρ(r)·r_i·r_j dV. У КУБА (и у равномерной сетки в нём)
     * эта матрица кратна единичной: внедиагональные члены нечётны и зануляются,
     * диагональные равны между собой по симметрии куба. Значит момент равен
     * m·d при m > 0 — точно, а не приближённо, и независимо от того, как
     * гибрид повёрнут относительно осей сетки.
     *
     * У сферически симметричной 2s оси нет; отдаётся (0, 0, 1).
     */
    Vec3 axis() const;
};

/**
 * Скалярное произведение двух орбиталей, посчитанных на одной сетке:
 * ∫ψ₁ψ₂ dV. Для орбитали с собой — проверка нормировки.
 */
double overlap(const OrbitalGrid& a, const OrbitalGrid& b);

/** Одна орбиталь. Для Orbital::S направление не используется. */
OrbitalGrid orbitalGrid(Orbital kind, const Vec3& dir, const Vec3& center,
                        const OrbitalOptions& options);

/**
 * Несколько орбиталей одного атома сразу.
 *
 * Радиальная часть (корень и экспонента в каждом узле) от направления не
 * зависит, а стоит она почти всего расчёта — поэтому считается один раз на
 * все направления. Для четырёх гибридов это втрое быстрее четырёх вызовов
 * orbitalGrid.
 */
std::vector<OrbitalGrid> orbitalGrids(Orbital kind, const std::vector<Vec3>& dirs,
                                      const Vec3& center, const OrbitalOptions& options);

}  // namespace chem
