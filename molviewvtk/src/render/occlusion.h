#pragma once

/**
 * ЗАГОРОЖЕНА ЛИ ТОЧКА ШАРАМИ СЦЕНЫ
 *
 * Подписи рисует GDI+ поверх готового кадра VTK, и никакой общей глубины у них
 * нет: подпись дальнего атома ложится поверх ближнего шара, хотя должна за ним
 * скрыться. Спрашивать глубину у видеокарты — лишнее чтение кадра на каждый
 * кадр; вместо этого видимость считается напрямую.
 *
 * Сцена состоит из шаров, а пересечение луча с шаром — квадратное уравнение.
 * Пускаем луч от глаза к точке и смотрим, не влезает ли по дороге чужой шар.
 *
 * Связи в расчёт НЕ берутся. Они тонкие (0,115 Å против 0,26–0,34 Å у шаров)
 * и почти всегда закрыты самими шарами, а вот ложные срабатывания дали бы
 * охотно: связь выходит из центра атома, то есть ровно из той точки, видимость
 * которой проверяется для его подписи.
 *
 * Про VTK этот файл не знает ничего — это чистая геометрия.
 */

#include <vector>

#include "chem/vec.h"

namespace render {

class Occluder {
public:
    void clear() { spheres.clear(); }
    void add(const chem::Vec3& center, double radius) { spheres.push_back({center, radius}); }

    /**
     * Видна ли точка из положения глаза.
     * ignore — номер шара, который не учитывать: подпись элемента стоит в
     * центре собственного шара, и без этого она была бы закрыта всегда.
     */
    bool visible(const chem::Vec3& eye, const chem::Vec3& point, int ignore = -1) const;

    /**
     * Видна ли плашка целиком. Проверяются центр и четыре угла прямоугольника,
     * лежащего в плоскости, перпендикулярной взгляду: иначе подпись, закрытая
     * наполовину, продолжала бы читаться поверх чужого шара.
     *
     * halfWidth и halfHeight — в ангстремах, right и up — оси камеры в мировых
     * координатах.
     */
    bool rectVisible(const chem::Vec3& eye, const chem::Vec3& center, double halfWidth,
                     double halfHeight, const chem::Vec3& right, const chem::Vec3& up,
                     int ignore = -1) const;

private:
    struct Sphere {
        chem::Vec3 center;
        double radius = 0;
    };
    std::vector<Sphere> spheres;
};

}  // namespace render
