#!/usr/bin/env bash
#
# СБОРКА ДИСТРИБУТИВА
#
# Делает каталог distr/, который можно скопировать на любую машину с Windows
# и запустить: ни MSYS2, ни VTK там не нужны. Это критерий готовности 8 из
# ЗАДАНИЕ.md, и готового средства у VTK для этого нет — отсюда скрипт.
#
# Запускать из оболочки MINGW64: список зависимостей снимается через ldd,
# а он живёт там же, где и g++, которым собрана VTK. Из PowerShell:
#
#     $env:MSYSTEM='MINGW64'
#     & C:\msys64\usr\bin\bash.exe -lc "/c/git/fun/molviewvtk/tools/distr.sh"
#
# Ключи:
#   --with-tests   положить рядом и консольные проверки (они статические,
#                  своих DLL не тянут) — чтобы сверку с эталоном можно было
#                  прогнать на чужой машине
#   --no-build     не пересобирать, взять то, что уже лежит в build/
#   --force        очистить distr/, даже если он не похож на наш дистрибутив
#
# В проект НЕ входит: это инструмент, а не часть программы.

set -euo pipefail

withTests=no
build=yes
force=no
for arg in "$@"; do
    case "$arg" in
        --with-tests) withTests=yes ;;
        --no-build)   build=no ;;
        --force)      force=yes ;;
        *) echo "неизвестный ключ: $arg" >&2; exit 2 ;;
    esac
done

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
dist="$root/distr"

# Оболочку стоит проверить сразу. ldd есть не только в MSYS2 — свой приносит
# и Git Bash, и там он молча покажет три библиотеки вместо шестидесяти семи:
# VTK нет в его PATH, и до неразрешённых зависимостей дело не доходит. Такой
# дистрибутив соберётся, будет весить 3 МБ и не запустится нигде, кроме этой
# машины.
if [ "${MSYSTEM:-}" != "MINGW64" ]; then
    echo "ОШИБКА: запускать надо из оболочки MINGW64 (сейчас MSYSTEM=${MSYSTEM:-пусто})." >&2
    exit 1
fi

say() { printf '%s\n' "$*"; }

# ── 1. свежая сборка ────────────────────────────────────────────────────
if [ "$build" = yes ]; then
    if [ ! -f "$root/build/build.ninja" ]; then
        say "настраиваю сборку..."
        cmake -S "$root" -B "$root/build" -G Ninja >/dev/null
    fi
    say "собираю..."
    cmake --build "$root/build"
fi
if [ ! -f "$root/build/molview.exe" ]; then
    echo "ОШИБКА: нет build/molview.exe — сначала собрать." >&2
    exit 1
fi

# ── 2. чистое место ─────────────────────────────────────────────────────
# Стираем СОДЕРЖИМОЕ, а не сам каталог. Во-первых, rm -rf по каталогу, который
# назвал не я, — верный способ однажды снести чужое. Во-вторых, Windows держит
# каталог открытым ещё некоторое время после удаления файлов из него, и rm -rf
# по нему самому падает с «Device or resource busy» на ровном месте.
if [ -e "$dist" ] && [ -n "$(ls -A "$dist" 2>/dev/null)" ]; then
    if [ ! -e "$dist/molview.exe" ] && [ "$force" != yes ]; then
        echo "ОШИБКА: $dist не пуст и не похож на дистрибутив." >&2
        echo "Проверьте, что там, и уберите сами — или запустите с --force." >&2
        exit 1
    fi
    if ! find "$dist" -mindepth 1 -delete 2>/dev/null; then
        echo "ОШИБКА: не удалось очистить $dist." >&2
        echo "Чаще всего это запущенный molview.exe из этой же папки:" >&2
        echo "Windows не даёт заменить .exe и .dll, пока они загружены." >&2
        exit 1
    fi
fi
mkdir -p "$dist/data"

# ── 3. программа и данные ───────────────────────────────────────────────
cp "$root/build/molview.exe" "$dist/"
# Справочник элементов и база молекул. findDataFile ищет data/ рядом с .exe,
# поэтому подкаталог обязан называться именно так и лежать именно здесь.
cp "$root"/data/*.json "$dist/data/"

if [ "$withTests" = yes ]; then
    for name in selftest smilestest orbitaltest; do
        [ -f "$root/build/$name.exe" ] && cp "$root/build/$name.exe" "$dist/"
    done
fi

# ── 4. библиотеки ───────────────────────────────────────────────────────
# ldd обходит зависимости рекурсивно, поэтому хватает одного вызова: в выводе
# уже и VTK, и всё, что она тянет за собой. Берём только /mingw64 — системные
# DLL из C:\Windows на чужой машине и так есть, а копировать их нельзя.
say "собираю библиотеки..."
copied=0
while read -r lib; do
    [ -n "$lib" ] || continue
    cp "$lib" "$dist/"
    copied=$((copied + 1))
done < <(ldd "$root/build/molview.exe" | awk '{print $3}' | grep -i '^/mingw64/' | sort -u)

if [ "$copied" -eq 0 ]; then
    echo "ОШИБКА: ldd не нашёл ни одной библиотеки из /mingw64." >&2
    exit 1
fi

# ── 5. записка для того, кто получит папку ──────────────────────────────
readme="$dist/ЧИТАЙ.txt"
cat > "$readme" <<'КОНЕЦ'
СТРОЕНИЕ МОЛЕКУЛ — валентные углы и гибридизация по теории Гиллеспи

Запуск: molview.exe

Ставить ничего не нужно. Все библиотеки лежат в этой же папке, поэтому
папку надо копировать ЦЕЛИКОМ — один molview.exe без соседних файлов
не запустится.

Что внутри:
  molview.exe   программа
  data/         справочник элементов и база молекул, без неё не работает
  *.dll         VTK и стандартные библиотеки C++

Требуется: Windows 10 или 11, 64 бита, видеокарта с OpenGL 3.2.

Управление: перетаскивание — поворот, колесо — масштаб, щелчок по атому —
разбор его электронного строения. Панель внизу переключает стиль модели
и то, что показано: неподелённые пары, гибридные орбитали, дипольный
момент, валентные углы. Кнопка «Снимок» сохраняет картинку в PNG в папку
«Изображения».
КОНЕЦ

if [ "$withTests" = yes ]; then
    cat >> "$readme" <<'КОНЕЦ'

Проверки ядра — консольные, запускать из командной строки, чтобы увидеть
вывод: selftest.exe (сверка с эталоном по 89 молекулам), smilestest.exe
(разбор формул, которых нет в базе), orbitaltest.exe (волновые функции
и углы между гибридными орбиталями).
КОНЕЦ
fi

# Файл для Windows: метка UTF-8 в начале и переводы строк CRLF. Без метки
# «Блокнот» на чужой машине может прочитать русский текст как ANSI и показать
# кракозябры, без CRLF — слепить всё в одну строку. Восьмеричные коды, а не
# \xEF: их одинаково понимает и awk из MSYS2, и любой другой.
awk 'BEGIN { printf "\357\273\277" } { printf "%s\r\n", $0 }' "$readme" > "$readme.tmp"
mv "$readme.tmp" "$readme"

# ── 6. проверка, что папка самодостаточна ───────────────────────────────
# Windows ищет DLL сначала рядом с самой программой, поэтому ldd на КОПИИ
# показывает, чем она будет пользоваться на самом деле. Если там осталась
# ссылка в /mingw64 — значит что-то не скопировалось, и на чужой машине
# программа молча не запустится.
leftover=$(cd "$dist" && ldd molview.exe | awk '{print $3}' | grep -i '^/mingw64/' || true)
missing=$(cd "$dist" && ldd molview.exe | grep -i 'not found' || true)
if [ -n "$leftover" ] || [ -n "$missing" ]; then
    echo "ОШИБКА: дистрибутив неполон." >&2
    [ -n "$leftover" ] && { echo "осталась ссылка наружу:" >&2; echo "$leftover" >&2; }
    [ -n "$missing" ] && { echo "не найдено:" >&2; echo "$missing" >&2; }
    exit 1
fi

say ""
say "готово: $dist"
say "файлов: $(find "$dist" -type f | wc -l), из них библиотек: $copied"
say "размер: $(du -sh "$dist" | cut -f1)"
say "проверено: molview.exe берёт все библиотеки из самой папки"
